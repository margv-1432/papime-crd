src<-'datos/preparados/capitulo-01';checks<-list()
ck<-function(name,ok,detail){checks[[length(checks)+1L]]<<-list(prueba=name,correcta=isTRUE(ok),detalle=detail)}
states<-sf::st_read(file.path(src,'F01-estados.gpkg'),quiet=TRUE)
prov<-sf::st_read(file.path(src,'F01-provincias.gpkg'),quiet=TRUE)
ck('32entidades',nrow(states)==32L,nrow(states))
ck('15provincias',length(unique(prov$CLAVE))==15L,sort(unique(prov$CLAVE)))
e<-terra::rast(file.path(src,'F01-elevacion-1800m.tif'))
c<-terra::rast(file.path(src,'F02-climas-1800m.tif'));s<-terra::rast(file.path(src,'F02-suelos-1800m.tif'))
ck('Rejilla común',terra::compareGeom(e,c,stopOnError=FALSE)&&terra::compareGeom(e,s,stopOnError=FALSE),paste(nrow(e),ncol(e),paste(terra::res(e),collapse=',')))
ck('Resolución dibujo1800m',all(terra::res(e)==1800),terra::res(e))
ec<-terra::values(e);cv<-sort(unique(as.integer(terra::values(c))));sv<-sort(unique(as.integer(terra::values(s))))
ck('Clima dominio ráster',all(cv%in%1:10),cv)
ck('Suelo dominio ráster',all(sv%in%1:7),sv)
ck('Elevación dominio plausible',all(ec[is.finite(ec)]>=-100&ec[is.finite(ec)]<6000),range(ec,na.rm=TRUE))
ck('CRS proyectado compatible',!sf::st_is_longlat(states)&&terra::same.crs(e,terra::vect(states)),sf::st_crs(states)$input)
roads<-sf::st_read(file.path(src,'F01-carreteras-federales.gpkg'),quiet=TRUE)
rm<-jsonlite::read_json(file.path(src,'F01-caminos-metadatos.json'),simplifyVector=TRUE)
ck('Todos los segmentos viales retenidos',rm$segmentos_fuente==120863L&&rm$comprobaciones$segmentos_visitados==120863L,rm$segmentos_fuente)
ck('Cadenas viales íntegras',nrow(roads)==rm$cadenas_dibujo&&!any(sf::st_is_empty(roads)),nrow(roads))
versions<-list(sf=as.character(getNamespaceVersion("sf")),terra=as.character(getNamespaceVersion("terra")),jsonlite=as.character(getNamespaceVersion("jsonlite")))
jsonlite::write_json(list(fecha='2026-11-05',alcance='Geometría de dibujo;no prueba accesibilidad ni aptitud',pruebas=checks,total=length(checks),correctas=sum(vapply(checks,function(x)x$correcta,TRUE)),paquetes=versions), 'seguimiento/auditoria-geometria-F01-F02.json',pretty=TRUE,auto_unbox=TRUE)
stopifnot(all(vapply(checks,function(x)x$correcta,TRUE)))
cat('Auditoría geométrica:',length(checks),'pruebas correctas.\n')
